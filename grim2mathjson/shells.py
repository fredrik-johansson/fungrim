def _arity_field(arities):
    if not arities:
        return None
    lo, hi = min(arities), max(arities)
    return lo if lo == hi else [lo, hi]


def _usage_signature(name, census):
    arities = census.heads.get(name)
    if not arities:
        return None
    slots = census.arg_types.get(name, {})
    lo, hi = min(arities), max(arities)
    params = []
    for i in range(hi):
        t = slots.get(i) or "any"
        if i >= lo:
            t += "?"
        params.append(t)
    if any(slots.get(i) for i in range(hi)):
        return (params, "complex")
    return None


def build(result, entries, ce_known):
    """Returns (declarations_doc, uncovered_names).

    declarations_doc is the deterministic dict written to
    declarations.json; uncovered_names is the mechanical-coverage residue
    (must be empty for the M4 acceptance)."""
    shell_universe = set(mapping.SHELL_HEADS)
    census = run_census(result, vocabulary=shell_universe | set(ce_known))
    symdefs = collect_symbol_definitions(entries)

    # reverse SYMBOL_MAP: emitted name -> fungrim source names
    reverse = {}
    for src, dst in mapping.SYMBOL_MAP.items():
        if src != dst:
            reverse.setdefault(dst, []).append(src)

    names = census.all_names()

    to_declare = sorted(n for n in names
                        if n not in ce_known and n in shell_universe)
    uncovered = sorted(n for n in names
                       if n not in ce_known and n not in shell_universe)

    declarations = {}
    for name in to_declare:
        fungrim_names = [name] + sorted(reverse.get(name, []))
        sd = next((symdefs[fn] for fn in fungrim_names if fn in symdefs),
                  None)
        arities = census.heads.get(name, set())
        is_function = bool(arities)
        if sd is not None and sd["example"] is not None \
                and not sd["example"].is_atom():
            arities = set(arities) | {len(sd["example"].args())}

        signature = None
        source = None
        domain_table = None
        if sd is not None and sd["table"] is not None:
            domain_table = translated_domain_table(sd["table"])

        if name in mapping.VERIFIED_SHELLS:
            signature = mapping.VERIFIED_SHELLS[name]
            source = "verified"
        if signature is None and sd is not None and sd["table"] is not None:
            derived = signature_from_table(
                name, set(fungrim_names), sd["table"],
                min(arities) if arities else None)
            if derived is not None:
                params, codomain = derived
                signature = f"({', '.join(params)}) -> {codomain}" \
                    if params else codomain
                source = "table"
        if signature is None and name in CURATED_SIGNATURES:
            signature = CURATED_SIGNATURES[name]
            source = "curated"
        if signature is None and is_function:
            derived = _usage_signature(name, census)
            if derived is not None:
                params, codomain = derived
                signature = f"({', '.join(params)}) -> {codomain}"
                source = "usage"
        if signature is None:
            signature = "(any+) -> any" if is_function else "any"
            source = "fallback"

        rec = {
            "fungrimId": sd["id"] if sd else None,
            "description": sd["description"] if sd else None,
            "arity": _arity_field(arities),
            "signature": signature,
            "signatureSource": source,
            "signatureInferred": source != "fallback",
            "domainTable": domain_table,
            "wikidata": None,
        }
        extra = [fn for fn in fungrim_names if fn != name]
        if extra:
            rec = {"fungrimNames": extra, **rec}
        declarations[name] = rec

    # CE-known heads used by the corpus: audit section
    existing = {}
    for name in sorted(names & ce_known):
        rec = {}
        if name in reverse:
            rec["fungrimNames"] = sorted(reverse[name])
        if name in ("Erf", "Erfc"):
            rec["note"] = ("CE numeric kernel is ~1e-7 accurate "
                           "(SPIKE-DECISIONS.md #15); tolerance >= 1e-6 "
                           "for numeric validation")
        existing[name] = rec

    doc = {
        "generator": GENERATOR,
        "declarations": declarations,
        "existing": existing,
    }
    return doc, uncovered


def write(doc, outdir):
    path = os.path.join(outdir, "declarations.json")
    with open(path, "w", newline="\n") as f:
        json.dump(doc, f, indent=1, ensure_ascii=True)
        f.write("\n")


def summarize(doc):
    decls = doc["declarations"]
    by_source = {}
    for rec in decls.values():
        by_source[rec["signatureSource"]] = \
            by_source.get(rec["signatureSource"], 0) + 1
    return {
        "shellCount": len(decls),
        "existingCount": len(doc["existing"]),
        "signatureSources": dict(sorted(by_source.items())),
        "withDomainTable": sum(1 for r in decls.values()
                               if r["domainTable"]),
    }
