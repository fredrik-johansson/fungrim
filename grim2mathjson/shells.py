"""Symbol-shell declaration table -> declarations.json (M4, plan SS4).

Inputs:
- the SymbolDefinition entries of ``all_entries`` (228 in this snapshot;
  48 carry a domain/codomain Table -- far fewer than the live fungrim.org,
  so usage-derived signatures supplement the table-derived ones),
- the in-memory translation result (corpus + properties records) for the
  head/atom census, call-site arities and per-argument type evidence,
- ``ce-known-symbols.txt``: the oracle of names the Compute Engine already
  defines, generated by ``npx tsx grim2mathjson/gen_ce_known.ts`` (keeps
  the two repos decoupled, plan SS4 "Filtering").

Output ``<out>/declarations.json``:

    {
      "generator": "...",
      "declarations": { <name>: {
          "fungrimId":       SymbolDefinition entry id | null,
          "fungrimNames":    source names when != <name> (e.g. PP->Primes),
          "description":     SymbolDefinition text | null,
          "arity":           int | [min, max] | null (atoms),
          "signature":       CE type string (feeds ce.declare directly),
          "signatureSource": "verified" | "table" | "usage" | "curated"
                             | "fallback",
          "signatureInferred": false only for "fallback",
          "domainTable":     translated Table rows | null,
          "wikidata":        null (hand-curated overlay is M6)
      } },
      "existing": { <CE-known name used by the corpus>: {
          "fungrimNames": [...], "note": ... } }
    }

Signature priority (first applicable wins):
1. ``verified``  -- mapping.VERIFIED_SHELLS, ce.declare-verified in the M0
   spike (incl. the boolean predicates Element's EL-3 form requires).
2. ``table``     -- derived from the "Numbers" rows of the entry's domain
   Table via the set->type map below; per-position join across rows;
   trailing positions beyond the minimum corpus call-site arity are
   marked optional (``integer?``).
3. ``curated``   -- hand-table for heads whose first argument is a
   function literal (generator/extremum heads emitted by structural.py)
   and for non-numeric atoms/domains; documented inline.
4. ``usage``     -- parameter types joined from corpus call sites
   (literal ints -> integer, variables -> the type of their Element
   assumption domain); codomain "complex" (Fungrim shells are
   number-valued unless curated otherwise).
5. ``fallback``  -- ``(any+) -> any`` / ``any``; signatureInferred false.

The mechanical coverage cross-check (M4 acceptance) lives in
:func:`build`: every head/atom occurring in an emitted expression that is
neither CE-known nor a per-entry variable MUST be covered by the
declarations table; leftovers are returned for the caller to fail on.
"""

