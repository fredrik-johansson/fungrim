GENERATOR = f"grim2mathjson {__version__}"

_FUSED_SUBSCRIPT = re.compile(r"^(.+?)_\d+$")

# Type-width join order (CE numeric tower fragment used here).
_TYPE_ORDER = ["integer", "rational", "real", "complex"]


def _join(a, b):
    if a is None:
        return b
    if b is None:
        return a
    if a == b:
        return a
    if a in _TYPE_ORDER and b in _TYPE_ORDER:
        return _TYPE_ORDER[max(_TYPE_ORDER.index(a), _TYPE_ORDER.index(b))]
    return "any"


