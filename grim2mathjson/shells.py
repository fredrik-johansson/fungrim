def _head_name(e):
    if e.is_atom():
        return None
    h = e.head()
    return h._symbol if (h.is_atom() and h.is_symbol()) else None


def _fungrim_set_type(S):
    """CE type of a Fungrim domain-set Expr (None: not a plain number set)."""
    if S.is_atom() and S.is_symbol():
        return {"ZZ": "integer", "QQ": "rational", "RR": "real",
                "CC": "complex", "PP": "integer", "HH": "complex",
                "AlgebraicNumbers": "complex"}.get(S._symbol)
    h = _head_name(S)
    if h in ("ZZGreaterEqual", "ZZLessEqual", "Range"):
        return "integer"
    if h in ("OpenInterval", "ClosedInterval", "OpenClosedInterval",
             "ClosedOpenInterval"):
        return "real"
    if h == "SetMinus":
        return _fungrim_set_type(S.args()[0])
    if h == "Union":
        t = None
        for a in S.args():
            ta = _fungrim_set_type(a)
            if ta is None:
                return None
            t = _join(t, ta)
        return t
    return None


def _table_rows(table):
    """Yield (section, P, Q) for each Tuple(P, Q) row of a domain Table."""
    rows = []
    for a in table.args():
        if _head_name(a) == "List":
            section = None
            for item in a.args():
                ih = _head_name(item)
                if ih == "TableSection":
                    section = item.args()[0]._text \
                        if item.args() and item.args()[0].is_text() else None
                elif ih == "Tuple" and len(item.args()) == 2:
                    rows.append((section, item.args()[0], item.args()[1]))
    return rows


def _flatten_and(P):
    if _head_name(P) == "And":
        out = []
        for a in P.args():
            out.extend(_flatten_and(a))
        return out
    return [P]


def signature_from_table(name, fungrim_names, table, min_arity):
    """(params, codomain) derived from the "Numbers" rows, or None.

    Rows mentioning power series / infinities / structural domains yield no
    type via _fungrim_set_type and are excluded from the primary signature
    (they remain visible in the emitted domainTable)."""
    by_arity = {}
    codomain = None
    for section, P, Q in _table_rows(table):
        if section not in (None, "Numbers"):
            continue
        if _head_name(Q) != "Element" or len(Q.args()) != 2:
            continue
        call, cod = Q.args()
        if call.is_atom():
            # atom definition row: Element(C, RR) etc.
            if call.is_symbol() and call._symbol in fungrim_names:
                t = _fungrim_set_type(cod)
                if t is not None:
                    codomain = _join(codomain, t)
            continue
        if _head_name(call) not in fungrim_names:
            continue
        args = call.args()
        if any(not (a.is_atom() and a.is_symbol()) for a in args):
            continue
        # build per-arg types from P's Element conjuncts
        elems = {}
        for c in _flatten_and(P):
            if _head_name(c) == "Element" and len(c.args()) == 2 \
                    and c.args()[0].is_atom() and c.args()[0].is_symbol():
                elems[c.args()[0]._symbol] = c.args()[1]
        types = []
        for a in args:
            S = elems.get(a._symbol)
            t = _fungrim_set_type(S) if S is not None else None
            if t is None:
                types = None
                break
            types.append(t)
        if types is None:
            continue
        cod_t = _fungrim_set_type(cod)
        if cod_t is None:
            continue
        slots = by_arity.setdefault(len(types), [None] * len(types))
        for i, t in enumerate(types):
            slots[i] = _join(slots[i], t)
        codomain = _join(codomain, cod_t)
    if not by_arity:
        if codomain is not None:
            return ([], codomain)  # atom (constant) definition
        return None
    max_arity = max(by_arity)
    params = [None] * max_arity
    for arity, slots in by_arity.items():
        for i, t in enumerate(slots):
            params[i] = _join(params[i], t)
    params = [t or "any" for t in params]
    optional_from = min(min(by_arity), min_arity or max_arity)
    params = [t + "?" if i >= optional_from else t
              for i, t in enumerate(params)]
    return (params, codomain or "complex")


def translated_domain_table(table):
    """All Table rows as MathJSON (untranslatable rows keep source strings)."""
    out = []
    for section, P, Q in _table_rows(table):
        row = {"section": section}
        for key, expr in (("domain", P), ("codomain", Q)):
            try:
                row[key] = walker.walk(expr, walker.Ctx())
            except (walker.TranslationSkip, walker.UnknownHeadError):
                row[key] = None
                row[key + "Source"] = str(expr)
        out.append(row)
    return out or None


