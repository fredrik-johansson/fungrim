_CONSTANT_TYPES = {
    "Pi": "real", "ExponentialE": "real", "EulerGamma": "real",
    "CatalanConstant": "real", "GoldenRatio": "real",
    "PositiveInfinity": "real", "NegativeInfinity": "real",
    "ImaginaryUnit": "complex", "ComplexInfinity": "complex",
}

_DOMAIN_TYPES = {
    "Integers": "integer", "NonNegativeIntegers": "integer",
    "PositiveIntegers": "integer", "NonPositiveIntegers": "integer",
    "Primes": "integer", "RationalNumbers": "rational",
    "RealNumbers": "real", "ComplexNumbers": "complex",
    "HH": "complex", "AlgebraicNumbers": "complex",
}


def _domain_type(d):
    """CE type of a translated membership domain (None when not numeric)."""
    if isinstance(d, str):
        return _DOMAIN_TYPES.get(d)
    if isinstance(d, list) and d and isinstance(d[0], str):
        if d[0] in ("Interval",):
            return "real"
        if d[0] in ("Range", "Divisors"):
            return "integer"
        if d[0] == "SetMinus":
            return _domain_type(d[1])
        if d[0] == "Union":
            t = None
            for a in d[1:]:
                t = _join(t, _domain_type(a))
            return t
    return None


# Encoding markers that are not standalone symbols: "Open" only exists as
# Interval endpoint syntax (["Interval", ["Open", a], b], spike #10) and is
# interpreted positionally by CE's Interval -- it needs no declaration.
_STRUCTURAL_MARKERS = frozenset(["Open"])


class Census:
    """Names/arities/argument-type evidence over the emitted expressions."""

    def __init__(self):
        self.heads = {}        # name -> set of arities
        self.atoms = set()
        self.arg_types = {}    # name -> {position: joined type | None}

    def _record_call(self, name, args, var_types):
        self.heads.setdefault(name, set()).add(len(args))
        slots = self.arg_types.setdefault(name, {})
        for i, a in enumerate(args):
            t = None
            if isinstance(a, int):
                t = "integer"
            elif isinstance(a, dict) and "num" in a:
                t = "real"
            elif isinstance(a, str):
                t = var_types.get(a) or _CONSTANT_TYPES.get(a)
            if t is not None:
                slots[i] = _join(slots.get(i), t)
            else:
                slots.setdefault(i, None)

    def scan_record(self, record, presumed_variables=None):
        """Census one corpus/property record.

        Bound names are collected record-wide first (a binder's body is a
        *sibling* of the binding form -- ["Sum", body, ["Limits", "k", ...]]
        -- so lexical-scope tracking would miss the body occurrences; a
        record-local name never doubles as a shell head, so record-wide
        exclusion is safe).

        ``presumed_variables``: property records carry no ``variables``
        list (the M2 micro-format is frozen), so free parameter names
        (q, chi, ...) cannot be excluded structurally; the caller passes
        the known-vocabulary set and anything outside it is presumed to
        be a variable. Their function heads are all explicit vocabulary,
        so shell coverage is unaffected.
        """
        excluded = set(record.get("variables") or [])
        excluded |= set(record.get("indexedFamilies") or [])
        if record.get("var"):
            excluded.add(record["var"])

        def expr_fields():
            for field in ("formula", "assumptions", "expr", "domain",
                          "point", "condition", "value"):
                v = record.get(field)
                if v is not None:
                    yield v
            # alternative assumption sets (list of exprs; the scanners
            # treat a non-symbol head as a transparent container)
            for v in record.get("assumptionAlternatives") or []:
                yield v
            for v in record.get("path") or []:
                yield v

        # pass 1: record-wide binder collection
        def collect_binders(x):
            if not isinstance(x, list) or not x:
                return
            head = x[0]
            if isinstance(head, str):
                if head == "Function":
                    excluded.update(a for a in x[2:] if isinstance(a, str))
                elif head in ("Limits", "ForAll", "Exists", "Element") \
                        and len(x) > 1 and isinstance(x[1], str):
                    # statement-position Element vars are free (already in
                    # `variables`); indexing-set vars are bound -- both are
                    # record-local names, so excluding both is safe.
                    excluded.add(x[1])
            for a in (x if not isinstance(head, str) else x[1:]):
                collect_binders(a)

        for v in expr_fields():
            collect_binders(v)

        # variable -> type evidence from every ["Element", var, S] in the
        # record: assumption conjuncts AND indexing sets inside the formula
        # (a Sum's bound index has its domain in the indexing set, not the
        # assumptions).
        var_types = {}
        def collect_types(x):
            if not isinstance(x, list) or not x:
                return
            if x[0] == "Element" and len(x) >= 3 and isinstance(x[1], str):
                t = _domain_type(x[2])
                if t is not None:
                    var_types[x[1]] = _join(var_types.get(x[1]), t)
            if x[0] in ("Sum", "Product", "Integrate"):
                # ["Limits", v, lo, hi]: discrete for Sum/Product,
                # continuous for Integrate
                for a in x[1:]:
                    if isinstance(a, list) and len(a) >= 2 \
                            and a[0] == "Limits" and isinstance(a[1], str):
                        t = "integer" if x[0] != "Integrate" else "real"
                        var_types[a[1]] = _join(var_types.get(a[1]), t)
            for a in x:
                collect_types(a)
        for v in expr_fields():
            collect_types(v)

        def is_excluded(name):
            if name in excluded:
                return True
            m = _FUSED_SUBSCRIPT.match(name)
            if m and (m.group(1) in excluded
                      or m.group(1) + "_" in excluded):
                return True  # fused subscript symbol (z_1 of variable z)
            if presumed_variables is not None \
                    and name not in presumed_variables:
                return True
            return False

        # pass 2: heads/atoms census
        def scan(x):
            if isinstance(x, str):
                if not is_excluded(x):
                    self.atoms.add(x)
                return
            if not isinstance(x, list) or not x:
                return
            head = x[0]
            if isinstance(head, str):
                if head in _STRUCTURAL_MARKERS:
                    for a in x[1:]:
                        scan(a)
                    return
                if not is_excluded(head) and not head.endswith("_"):
                    self._record_call(head, x[1:], var_types)
                for a in x[1:]:
                    scan(a)
            else:
                for a in x:
                    scan(a)

        for v in expr_fields():
            scan(v)

    def all_names(self):
        return set(self.heads) | self.atoms


def run_census(result, vocabulary):
    census = Census()
    for records in result["corpus"].values():
        for r in records:
            census.scan_record(r)
    for r in result["properties"]:
        census.scan_record(r, presumed_variables=vocabulary)
    return census


