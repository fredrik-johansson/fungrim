def _named_parts(entry):
    out = {}
    for a in entry.args():
        if not a.is_atom():
            h = a.head()
            if h.is_atom() and h.is_symbol():
                out.setdefault(h._symbol, []).append(a)
    return out


def collect_symbol_definitions(entries):
    """name -> {"id", "example" (Expr), "description", "table" (Expr|None)}
    for every non-Formula SymbolDefinition entry."""
    defs = {}
    for e in entries:
        p = _named_parts(e)
        if "SymbolDefinition" not in p or "Formula" in p:
            continue
        sd = p["SymbolDefinition"][0]
        sym = sd.args()[0]
        if not (sym.is_atom() and sym.is_symbol()):
            continue
        eid = p["ID"][0].args()[0]._text if "ID" in p else None
        example = sd.args()[1] if len(sd.args()) > 1 else None
        descr = None
        if len(sd.args()) > 2 and sd.args()[2].is_text():
            descr = sd.args()[2]._text
        table = p["Table"][0] if "Table" in p else None
        defs[sym._symbol] = {
            "id": eid, "example": example,
            "description": descr, "table": table,
        }
    return defs


